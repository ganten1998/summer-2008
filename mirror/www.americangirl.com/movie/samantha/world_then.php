				<p class="ttlThen">Making a Splash</p>
				<p>Swimming was becoming a popular sport in 1904. When Samantha&#8217;s mother was growing up, swimming was not considered proper for girls or women, but people did think bathing&#8212;just going into the water&#8212;was healthy. By the early 1900s, people realized the benefits of exercise, but modesty was still very important. Bathing dresses looked a lot like party dresses. They covered a girl from head to toe and were made of wool. When they got wet, the dresses could weigh eight pounds. That&#8217;s as heavy as a gallon of milk. Imagine how hard it was to swim! Women were first allowed to swim in the Olympic Games in 1912. In the 2004 games, women competed in swimming, diving, synchronized swimming, and water polo.</p>
				
				<p class="ttlThen">Do the Subway</p>
				<p>The first subway opened in New York City in 1904. More than 30,000 men had spent four years tunneling through solid bedrock and under buildings to provide the crowded city with a new way to travel. On October 27, 1904, 150,000 people&#8212;many dressed up in their very best clothes&#8212;paid a nickel each to &#8220;do the subway.&#8221; Today, it costs two dollars to ride the longest subway in the world. Over 7 million people travel the more than 700 miles of track each weekday.</p>
				
