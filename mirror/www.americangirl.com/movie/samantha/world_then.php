				<span class="dropCap">G</span>rowing up in 1904 was different from growing up today. Girls like Samantha lived without computers, television, or CD players. Proper young ladies wore dresses and stockings, even when they played sports. Explore some of the other ways life has changed in the last century.
				<p class="ttlThen">You&#8217;ve Got Mail<p>
				<p>In 1904, people kept in touch by writing letters, sending more than 7 billion pieces of mail through the post office. They sent 63 million telegrams. Telephones were a relatively new invention and only 8 percent of homes had one. Today more than 90 percent of homes in the United States have a phone. There are over 159 million mobile phones, and 33 percent of children have one of their own. In one year, an estimated 9 trillion e-mails travel around the world!</p>
				
				<p class="ttlThen">What&#8217;s for Dinner?</p>
				<p>In Samantha&#8217;s time dinner was an elegant affair for well-to-do families. The menu usually included soup, fish, two kinds of meat, potatoes, vegetables, and several desserts. With so much food, a meal could last for more than three hours! Samantha would have made sure her appearance was spotless before joining Grandmary in the crystal- and silver-filled dining room. She practiced her very best manners by tilting her soup spoon away from her soup plate, keeping her elbows close to her sides, and not spilling a drop or a crumb. Dinner today isn&#8217;t as formal as it was in 1904. Families don&#8217;t always have time to eat together, and sometimes dinner comes from a drive-through restaurant on the way to after-school lessons and games. The idea of eating in an automobile would have shocked Grandmary, but today it&#8217;s quite common. What is dinnertime like at your house? How does your family make meals together special?</p>
				
