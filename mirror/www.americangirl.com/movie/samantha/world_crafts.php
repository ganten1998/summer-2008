				<p class="hdrCrafts">Directions:</p>
				Use acrylic paint to color the bottom of a cardboard box. Using a glue stick, cover the top and sides of the lid with glue, then cover with tissue paper, folding the excess paper inside the lid. Let both pieces dry. Make a tassel by cutting a piece of cardboard 3 inches long. Wrap yarn around it lengthwise 15 to 20 times.	Cut a 6-inch piece of yarn, loop it through the top of the tassel, and tie a knot. Slide the tassel off the cardboard. Wrap another piece of yarn around the tassel near the top and knot it. Have an adult help you cut through the bottom loop with sharp scissors. Thread a bead onto the yarn at the top of the tassel. Have an adult punch a hole in the center of the box lid. Thread the ends of the tassel through a button, then through the hole in the lid. Knot the yarn and tape it to the inside of the lid.</td>
