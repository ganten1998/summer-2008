		<div id="txtPartyMain">
				<span class="dropCap">H</span>ost a Felicity movie party! Invite your friends to an afternoon or evening of colonial-inspired games and treats. Plan your party for the weekend before the movie airs, or gather everyone together on November 29 to have a premiere party for <em>Felicity: An American Girl Adventure</em>.
			<div id="partyContent">
				<img src="assets/images/world/party/img_invite.jpg" alt="" width="140" height="118" class="party" border="0">
				<img src="assets/images/world/party/hdr_invitation.gif" alt="" width="87" height="23" border="0" title="Invitations">
				<p>Create an elegant invitation for each of your guests about ten days before your party. For a touch of colonial class, deliver the invitations in person.</p>
				<br><br><br>
				<p class="hdrParty">Directions:</p>
				<p>Use tan paper that looks like parchment. Write the invitation in your best handwriting, roll up the paper, and tie it with a bright ribbon. Here&#8217;s a sample of how an invitation would have been worded in Felicity&#8217;s time:</p>
				<blockquote>Miss Jennifer Hanson presents her compliments to Miss Julie Kasper<br>
				and requests the favor of her attendance at a Felicity movie party at<br>
				123 Hill Avenue on Tuesday, November 29, at 6:00 in the evening.</blockquote><br>
				
				<img src="assets/images/world/party/img_parlor.jpg" alt="" width="129" height="137" class="party" border="0">
				<img src="assets/images/world/party/hdr_parlgames.gif" alt="" width="113" height="26" border="0" title="Parlor Games">
				<p class="hdrParty">When Felicity was growing up, families and friends gathered in the parlor for music, stories, and games.</p>
				<p class="hdrParty">Try these Colonial games along with your favorite contemporary party pastimes:</p>
				<p class="hdrParty">Hide the Thimble:</p> Everyone leaves the room except for one person. She hides a thimble somewhere in the room. Then the group returns to look for it. The person who finds the thimble wins a small prize. Then she gets to hide the thimble (If you don&#8217;t have a thimble, any small object will work).
				<p class="hdrParty">Hunt the Ring:</p> The players sit on the floor and form a circle around one player. She closes her eyes. The players in the circle keep their hands hidden while they pass a ring back and forth behind their backs. When the player in the middle says &#8220;stop,&#8221; she opens her eyes and tries to guess who has the ring. If she guesses right, the players switch places.
				<p class="hdrParty">Frog in the Middle:</p> One person is chosen to be the Frog. She sits on a stool while the other players dance around her, chanting, &#8220;Frog in the middle, you can&#8217;t catch me!&#8221; Frog has to try to catch someone without leaving the stool. The person who is caught becomes the next Frog.<br><br><br>

				<img src="assets/images/world/party/img_refresh.jpg" alt="" width="172" height="120" class="party" border="0">
				<img src="assets/images/world/party/hdr_refresh.gif" alt="" width="110" height="27" border="0" title="Refreshments">
				<p class="hdrParty">No party is complete without treats! Serve your favorite refreshments or try some of the sweets Felicity enjoyed.</p>
				<p><span class="hdrParty">Liberty Tea:</span> Place 3 teaspoons dried raspberry leaves* in a teapot. Ask an adult to pour 6 cups of boiling water over the leaves. Let the tea steep for 5 minutes. Use a strainer to catch the tea leaves as you pour the tea into teacups. Sweeten the tea with honey and milk.<br> 
				<em>*Available at health-food and import stores and at some supermarkets.</em></p>
				<p><span class="hdrParty">Cranberry-Apple Punch:</span> Have an adult help you mix together 2 quarts of cranberry juice, 1 pint of apple juice, and 1 pint of lemonade. Pour the punch into a pretty pitcher, add ice, and serve.</p> 
				<p><span class="hdrParty">Sugar Cookies:</span> Buy a tube of refrigerated sugar-cookie dough. Roll out the dough, and then use cookie cutters to cut out shapes such as hearts, stars, and moons. In a small bowl, mix 2 tablespoons of nutmeg and 2 tablespoons of sugar. Sprinkle the sugar mixture on the cookies. Have an adult help you bake the cookies according to the package directions.</p>
				<p><span class="hdrParty">Spiced Nuts:</span><br>
				<div id="ingred"><span class="hdrParty">You will need:<br>
					Ingredients</span><br>
					Shortening or butter<br>
					1 cup sugar<br>
					4 tablespoons cinnamon<br>
					1/2 teaspoon nutmeg<br>
					2 eggs<br>
					1 cup pecans<br>
					1 cup almonds
				</div>
					<div id="equip"><br>
					<span class="hdrParty">Equipment</span><br>
					2 cookie sheets<br>
					Waxed paper<br>
					Measuring cups and spoons<br>
					Paper bag<br>
					Mixing bowl<br>
					Spoon<br>
					Fork<br>
					Potholders<br>
					Nut or candy dish</div><br><br><br><br><br><br><br><br><br><br><br>
					<p><span class="hdrParty">Directions:</span><br></p>
					<p>1. Ask an adult to preheat the oven to 300&#176;. Use a piece of waxed paper and shortening or butter to grease the cookie sheets.</p>
					<p>2. Measure the sugar, cinnamon, and nutmeg into the paper bag. Hold the bag closed and gently shake it to mix the ingredients. </p>
					<p>3. Have an adult help you separate the egg whites into the bowl. Beat the whites with a fork until foaming. Stir a few of the nuts into the egg whites. </p>
					<p>4. Carefully spoon the nuts out of the egg whites and drop them into the bag. Hold the bag closed and gently shake it to coat the nuts with the sugar mixture. </p>
					<p>5. Place the nuts on the cookie sheet. Prepare the rest of the nuts in the same way. </p>
					<p>6. Bake the nuts for 30 minutes. Have an adult remove the cookie sheets from the oven. Let the nuts cool, and then serve them in a pretty nut or candy dish.</p>
