			<p>As soldiers fought overseas, Americans at home were &#8220;fighting on the home front.&#8221; People made many sacrifices in order to help win the war&#8212;they even changed the foods they ate. Americans stopped buying canned food to save on metal and turned their yards into &#8220;Victory gardens&#8221; so that farmers could grow food for soldiers. The government also <em>rationed</em>, or limited, the foods people could buy so that more could go to the soldiers and to our allies. Even everyday ingredients such as sugar, butter, and beef were rationed and hard to get, so people found creative ways to cook. With help from an adult, try some of these recipes to get a taste of cooking in Molly&#8217;s time.</p>
