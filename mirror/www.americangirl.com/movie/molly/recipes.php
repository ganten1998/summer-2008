		<div id="soup">
			<img src="assets/images/world/recipes/labelSoup.gif" width="158" height="28" alt="Victory Garden Soup" />
			<div id="ingredients">
				<p>Ingredients</p>
				<ul>
					<li>1 medium potato</li>
					<li>2 tablespoons butter</li>
					<li>1 small onion, chopped</li>
					<li>1 rib of celery, chopped</li>
					<li>2 tablespoons flour</li>
					<li>2 cups tomato juice</li>
					<li>1 cup water</li>
					<li>1/2 tablespoon salt</li>
					<li>1/2 teaspoon pepper</li>
					<li>1/4 cup alphabet macaroni</li>
					<li>1 large carrot, sliced</li>
					<li>1 medium turnip, diced</li>
					<li>1/2 cup corn</li>
					<li>1/2 cup peas</li>
					<li>1 tomato, diced</li>
					<li>3 lettuce leaves, chopped</li>
				</ul>
			</div>
			<div id="equipment">
				<p>Equipment</p>
				<ul>
					<li>Vegetable peeler</li>
					<li>Knife</li>
					<li>Cutting board</li>
					<li>Medium saucepan</li>
					<li>Fork</li>
					<li>Measuring cups and spoons</li>
					<li>Potato masher</li>
					<li>Large soup pot</li>
					<li>Wooden spoon</li>
				</ul>
			</div>
			<div id="directions">
			<img class="star" src="assets/images/world/recipes/starHand.gif" width="106" height="33">
				<p>Directions (6 servings)</p>
				<ol>
					<li>Peel the potato and cut it into small cubes.</li>
					<li>Put the potato pieces into the saucepan and add just enough cold water to cover them.</li>
					<li>Put the saucepan onto the stove and turn the burner to medium-high. When the water begins to <em>boil</em>, or bubble rapidly, turn the heat down. Let the potatoes <em>simmer</em>, or bubble gently, for 15 minutes.</li>
					<li>After 15 minutes, insert the fork into a potato piece. If it goes in easily, the potatoes are done.</li>
					<li>Let the potatoes cool for a few minutes. Using the potato masher, mash them with the cooking water.</li>
					<li>Put the butter into the soup pot and melt it over medium heat. Stir in the onions and celery. Cook them over low heat for about 5 minutes, stirring often.</li>
					<li>Add the flour to the butter, onions, and celery in the soup pot. Stir for 1 minute over low heat.</li>
					<li>Stir in the tomato juice, water, salt, pepper, and macaroni.</li>
					<li>Turn up the heat to medium high. Add the potatoes, carrots, turnips, corn, peas, and tomato.</li>
					<li>Cook the soup over medium-high heat, stirring occasionally. When it begins to boil, lower the heat and add the lettuce. Let the soup simmer for 20 minutes.</li>
				</ol>
			</div>
