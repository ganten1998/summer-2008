			<img class="star" src="assets/images/world/recipes/starHand.gif" width="106" height="33">
				<p>Directions (6 servings)</p>
				<ol>
					<li>Place 3 layers of paper towels on the counter next to the stove.</li>
					<li>Cut the cooked potatoes into thin slices. They will taste even better if the skins are left on!</li>
					<li>Coat the bottom of the skillet with oil or bacon drippings. Heat the skillet over medium-high heat.</li>
					<li>Cover the bottom of the skillet with potato slices. Sprinkle salt and pepper on them.</li>
					<li>When the bottoms of the slices are brown, use the spatula to turn them over to brown the other side.</li>
					<li>Use the spatula to put the fried potatoes on the paper towel to drain.</li>
					<li>Continue frying the rest of the potato slices in the same way. If the potatoes stick, add more oil or bacon drippings to the skillet.</li>
