		<div id="cupcakes">
			<img src="assets/images/world/recipes/labelCupcakes.gif" width="152" height="26" alt="Applesauce Cupcakes" />
			<div id="ingredients">
				<p>Ingredients</p>
				<ul>
					<li>2 cups flour, sifted</li>
					<li>1 teaspoon baking soda</li>
					<li>1/2 teaspoon ground nutmeg</li>
					<li>1/2 teaspoon ground cinnamon</li>
					<li>1/2 teaspoon ground cloves</li>
					<li>1/4 teaspoon salt</li>
					<li>1/3 cup shortening</li>
					<li>3/4 cup honey</li>
					<li>1 cup unsweetened applesauce</li>
					<li>1 cup seedless raisins</li>
					<li>1/4 cup broken walnut pieces</li>
					<li>Your favorite frosting</li>
				</ul>
			</div>
			<div id="equipment">
				<p>Equipment</p>
				<ul>
					<li>Cupcake or muffin pans</li>
					<li>16 paper cupcake liners</li>
					<li>Sifter</li>
					<li>Medium mixing bowl</li>
					<li>Measuring cups and spoons</li>
					<li>Large mixing bowl</li>
					<li>Electric mixer</li>
					<li>Rubber spatula</li>
					<li>Wooden spoon</li>
					<li>Pot holders</li>
					<li>Toothpick</li>
					<li>Wire cooling racks</li>
					<li>Butter knife</li>
				</ul>
			</div>
			<div id="directions">
				<img class="star" src="assets/images/world/recipes/starHand.gif" width="106" height="33">
				<p>Directions (6 servings)</p>
				<ol>
					<li>Preheat the oven to 350&deg;. Line the cupcake pans with paper liners.</li>
					<li>Put the sifter into the medium mixing bowl. Measure the sifted flour, baking soda, nutmeg, cinnamon, cloves, and salt into the sifter. Sift these dry ingredients into the bowl.</li>
					<li>Measure the shortening into the large mixing bowl. Use the electric mixer to beat the shortening until it is fluffy.</li>
					<li>Add the honey to the shortening and continue to beat the mixture for 2 minutes. Stop the mixer once or twice and use the rubber spatula to scrape down the sides of the bowl.</li>
					<li>Add half the applesauce and half the sifted dry ingredients to the honey-and-shortening mixture. Mix at medium speed until all the flour disappears. Stop once or twice to scrape down the sides of the bowl with the spatula.</li>
					<li>Add the remaining applesauce and dry ingredients. Mix again until everything is blended.</li>
					<li>Use the wooden spoon to stir in the raisins and walnut pieces.</li>
					<li>Spoon the batter into the cupcake liners, filling each about 2/3 full.</li>
					<li>Bake the cupcakes for 25 to 30 minutes.</li>
					<li>Poke a toothpick through the center of a cupcake. If the toothpick comes out clean, the cupcakes are done. Set them on the racks to cool.</li>
					<li>After 10 minutes, take the cupcakes out of the pans and let them cool completely on the racks before frosting them.</li>
				</ol>
			</div>
