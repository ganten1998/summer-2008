				<p>During the war, many common products were in short supply on the home front, so people had to be creative. Molly and her friends would have played simple games during parties. The prizes for winning a game might be a apples, something picked from the Victory Garden, or handfuls of peanuts.</p>
				<span>Movie-Title Charades</span>
				<p>Divide into two teams. On each team, players write down a movie title on each of ten individual slips of paper. Teams exchange their slips of paper and put them into a hat or bowl. Pick a team and a player from that team to go first. This person should select a slip of paper from her team&#8217;s movie choices. Without saying any words, the player should use actions to get her team to guess the title of the movie. Each player gets two minutes to help her team to guess correctly. One point is awarded for each correct guess given before time runs out. The team with the most points when all slips of paper are gone wins.</p>
				<span>Clothespins in a Bottle</span>
				<p>Place a glass bottle or jar with a small opening on the floor. Have each player stand in front of the bottle and try to drop ten clothespins into the jar, one at a time, without bending over. The player who drops in the most clothespins wins the game.</p>
				<span>Odds and Evens</span>
				<p>Players stand in the middle of the room. One side of the room is named &#8220;odds,&#8221; and the other side of the room is named &#8220;evens.&#8221; Play music from the 1940s. Everyone dances until the music stops. Each person runs to one side of the room or the other. Select someone to roll a die. If it lands on an even number, the people standing on the even side are out, and vice versa if an odd number is rolled. Keep playing until there is only one person leftthe winner!</p>
