					<h1>Molly&#8217;s Book Excerpt</h1>
				</div>
				<div id="main">
					<div id="excerpt">
						<p>From <em>Molly Saves the Day</em></p>
						<p id="opener">&#8220;I liked the way camp was before,&#8221; said Molly. &#8220;I don&#8217;t see why we have to mess everything up and go capturing flags.&#8221;</p>
						<p>&#8220;Especially in canoes,&#8221; added Susan.</p>
						<p>Linda shook her head. &#8220;The Color War is just a game. It&#8217;s supposed to be fun, not something to worry about. I mean, if we were going off to a real war or something, then I cold see being worried and scared.&#8221;</p>
						<p>Molly nodded. &#8220;My dad told us he was scared before he went away to war,&#8221; she said. &#8220;But he said it was okay to be scared because that meant he had a chance to be brave.&#8221;</p>
						<p>&#8220;Well, maybe this Color War will give us a chance to be brave,&#8221; said Linda. &#8220;If you can do something you&#8217;re scared to do, then you&#8217;re brave.&#8221;</p>
						<p>&#8220;That&#8217;s easy for you to say,&#8221; said Susan. &#8220;You&#8217;re not scared of canoeing like I am or swimming underwater like Molly is.&#8221;</p>
						<p>&#8220;Yeah,&#8221; said Molly, &#8220;you&#8217;re not scared of anything.&#8221;</p>
						<p>&#8220;Oh, yes I am,&#8221; said Linda.</p>
						<p>&#8220;Like what?&#8221; asked Susan.</p>
						<p>&#8220;Well,&#8221; said Linda, &#8220;it&#8217;s really stupid but I&#8217;m scared of creepy crawly things, like spiders and bugs. Worms are the worst.&#8221; Linda moved her fingers like wiggling worms and made a face so that Molly and Susan had to laugh. &#8220;Slimy worms! Ugh! I hate them!&#8221;</p>
						<p>&#8220;Really?&#8221; said Molly. It cheered her up to know that Linda was scared of something sort of silly, like worms.</p>
						<p>&#8220;Yes, really,&#8221; said Linda. &#8220;But at least I can joke about it. You don&#8217;t see me lying awake at night worrying about it. So don&#8217;t you two worry about Dorinda, or canoes, or swimming underwater. Don&#8217;t take this Color War so seriously. It won&#8217;t last forever, right?&#8221;</p>
						<p>&#8220;Right,&#8221; said Molly and Susan.</p>
						<p>&#8220;Okay,&#8221; said Linda. She rolled over and pulled her blankets up to her chin. &#8220;Go to sleep and that&#8217;s an order!&#8221;</p>
						<p>&#8220;Yes, sir!&#8221; giggled Susan. She rolled over and closed her eyes.</p>
						<p>Molly turned off her flashlight and closed her eyes, but she didn&#8217;t follow the order. She didn&#8217;t fall asleep for a long, long time. Linda wasn&#8217;t worried about the Color War, but Molly still was. Maybe the Color War would be her big chance to be brave. But she wondered if she really wanted that chance.</p>
