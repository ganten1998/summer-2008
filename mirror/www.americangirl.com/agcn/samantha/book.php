				<div id="main">
					<div id="excerpt">
						<p>From <em>Meet Samantha</em></p>
						<p id="opener">At four o&#8217;clock, Samantha stood outside the parlor doors looking like new. It was time for her hour with Grandmary. Samantha&#8217;s hair was combed, her ribbon was perfect, her skirt hung straight, and her stockings were repaired. She knocked softly on the door, then slipped though and made a quick curtsy to her grandmother.</p>
						<p>Samantha thought Grandmary looked like a queen, especially during their sewing hour. Grandmary sat up very straight. Her velvet chair looked like a throne with her silk gown flowing around it. Her white hair seemed made for a crown, with never a strand out of place.</p>
						<p>Samantha always tried to be a young lady, but it was a lot easier to remember how when Grandmary was watching. Samantha noticed that everyone behaved more like a lady when Grandmary was around.</p>
						<p>&#8220;Good afternoon, Samantha,&#8221; said Grandmary</p>
						<p>&#8220;Good afternoon, Grandmary.&#8221; Samantha squirmed ever so slightly. She didn&#8217;t know how, but Grandmary always seemed to know when she had been into mischief. But today, Grandmary didn&#8217;t ask questions. Instead, she smiled.</p>
						<p>&#8220;Come sit down, my dear,&#8221; Grandmary said. She handed a small basket to Samantha. &#8220;You must try to work a little harder on your sampler. It&#8217;s not going very quickly.&#8221;</p>
						<p>&#8220;Yes, Grandmary.&#8221; Samantha took her seat on a chair next to her grandmother. She picked up her sampler and sighed a little. When it was finished, the sampler would read &#8220;Actions speak louder than words.&#8221; Grandmary had explained this saying. She said it meant that how people act is more important than what they say. Samantha tried to imagine the words sewn in pink silk thread. Around them would be flowers and fruits made of complicated stitches that would show off her sewing skills. But the skills were slow in coming. So far the sampler read &#8220;Actions sp.&#8221;</p>
						<p>Samantha stuck her tongue between her lips as she concentrated on a hard stitch. She glanced sideways to see if her grandmother looked in a good mood.</p>
						<p>&#8220;Grandmary,&#8221; Samantha began.</p>
						<p>&#8220;Yes, dear?&#8221;</p>
						<p>&#8220;Did you see the doll in Schofield&#8217;s shop?&#8221; Samantha asked.</p>
						<p>&#8220;Yes, dear, I did,&#8221; answered Grandmary.</p>
						<p>&#8220;Isn&#8217;t she beautiful?&#8221; sighed Samantha.</p>
						<p>&#8220;It&#8217;s quite a nice doll,&#8221; Grandmary said.</p>
						<p>&#8220;Do you think I might have her?&#8221;</p>
						<p>&#8220;Samantha, that is an expensive doll,&#8221; said Grandmary. &#8220;It costs six dollars. If you are going to grow up to be a responsible young lady, you must understand the value of a dollar.&#8221;</p>
						<p>&#8220;I could earn the money to buy her, Grandmary. I could make boomerangs and sell them. The Boys&#8217; Handy Book shows just how to do it. I could&#8212;&#8221;</p>
						<p>&#8220;Samantha!&#8221; Grandmary was shocked. &#8220; A lady does not earn money.&#8221;</p>
						<p>Samantha had known there wasn&#8217;t much hope, but she added very quietly, &#8220;Cornelia says a woman should be able to earn money. She says women shouldn&#8217;t have to depend on men for everything. She says&#8212;&#8220;</p>
						<p>&#8220;Cornelia has a great many newfangled notions,&#8221; announced Grandmary. &#8220;She should keep them to herself.&#8221;</p>
