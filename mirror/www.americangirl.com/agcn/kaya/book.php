				<div id="main">
					<div id="excerpt">
						<p>From <em>Meet Kaya</em></p>
						<p id="opener">Speaking Rain was cautiously making her way through the elderberry bushes that grew along the riverbank. Kaya&#8217;s blind sister couldn&#8217;t know there was a steep bank on the other side of the bushes. &#8220;Stop, Speaking Rain!&#8221; Kaya called. She turned Steps High and started back. Speaking Rain didn&#8217;t seem to hear Kaya&#8217;s call. Were Stick People leading her astray? She kept going. &#8220;Stop! Don&#8217;t take another step!&#8221; Kaya cried.</p>
						<p>Now Speaking Rain heard Kaya&#8217;s cry. She stopped and turned. As she did, a piece of the bank crumbled beneath her feet. Speaking Rain fell backward. In a shower of stones, she tumbled into the swift river!</p>
						<p>Kaya drove Steps High forward. She jumped her over the bushes and reined her in sharply, her hooves plowing the ground. Speaking Rain was struggling in deep water, trying to swim toward shore. As she thrashed, a branch plunged down in the swift current and hit her. She went under. When she came up again, she was being pulled downstream in the powerful surge of the river.</p>
						<p>Fear struck through Kaya like a lightning flash. If Speaking Rain wasn&#8217;t pulled from the river, she&#8217;d drown. If Kaya tried to swim after her, they could both drown. To save Speaking Rain, Kaya&#8217;s only hope was to run her horse along the bank, try to get ahead of Speaking Rain, and ride into the river to catch her.</p>
						<p>Kaya gave her horse her head, then kicked her. Steps High burst forward. In a few strides she was at a full gallop. Kaya leaned low over her neck, clasping her horse with her knees. What if another piece of riverbank gave way? What if her horse bucked? Steps High lengthened out and tore around the next bend, then the next. She seemed as swift as a hawk diving from the sky! Now they were ahead of Speaking Rain, who flailed in the churning river. From here, Kaya had to get her horse into the water and then swim upstream to meet Speaking Rain as she was swept down.</p>
						<p>Would Steps High obey Kaya&#8217;s command to swim? Kaya dug her heels into her horse&#8217;s sides and again urged her forward. Steps High crossed the beach but paused at the edge of the water. &#8220;Come on, girl!&#8221; Kaya said, giving her another kick. </p>
