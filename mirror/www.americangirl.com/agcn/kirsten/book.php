				</div>
				<div id="main">
					<div id="excerpt">
						<p>From <em>Happy Birthday, Kirsten!</em></p>
						<p id="opener">Kirsten dished up a serving of stew for Mama, who rested in the bed with the baby. Mama wasn&#8217;t strong enough to work for very long yet, so Kirsten did most of Mama&#8217;s kitchen and farm chores. And there were new chores, too. Several times each day, Kirsten washed out the baby&#8217;s diapers and hung them to dry on the line outside. With all her work, Kirsten had no time to go to school. How lonely it was on the farm when Anna and Lisbeth were away all day. It seemed like years since Kirsten had sat in that sunny spot behind the schoolhouse, sewing with her friends. Every day she was home, she imagined them working on their squares without her. How she missed them and the fun of making the quilt.</p>
						<p>&#8220;Your friends from school will be here for the barn raising,&#8221; Mama said when she took her bowl of stew from Kirsten. &#8220;They&#8217;ll be coming with their parents. Each family will bring food, and Inger is going to make a huge kettle of venison stew for everyone.&#8221;</p>
						<p>That pleased Kirsten, though she didn&#8217;t see how she&#8217;d have time to play with the other girls. She&#8217;d probably have to help Mama with the extra work.</p>
						<p>&#8220;The families will be here all day, and after supper we&#8217;ll have music and dancing,&#8221; Mama went on &#8220;I can&#8217;t dance yet, but you and the others can.&#8221; Mama didn&#8217;t seem to mind about the dancing. She was smiling down at the baby who slept beside her.</p>
						<p>Mama tugged Kirsten&#8217;s braid. &#8220;I have something to ask you, dear.&#8221;</p>
						<p>Kirsten sighed. More work to do, she was sure. &#8220;Yes, Mama,&#8221; she said obediently.</p>
						<p>&#8220;Our barn raising will be on the day before your birthday. I thought you might like to do something special when your friends are here,&#8221; Mama said. &#8220;You&#8217;ve done the work of two women lately, and you deserve a day to play.&#8221;</p>
						<p>Kirsten took Mama&#8217;s hand. &#8220;A whole day with my friends?&#8221;</p>
						<p>Mama smiled. &#8220;Your tenth birthday should be a day of your own. A day to celebrate and to have fun.&#8221;</p>
						<p>Kirsten thought about picking wildflowers and playing games. And maybe there would be a cake to share. A barn raising and a birthday celebration, too! &#8220;May I run tell Lisbeth and Anna about it?&#8221; she asked Mama.</p>
						<p>Papa started to say something about washing up, but Mama said, &#8220;Dishes can wait.&#8221;</p>
						<p>&#8220;I&#8217;ll be right back,&#8221; Kirsten said and scooted out the door.</p>
						<p>As Kirsten ran to the other house, a wood thrush called and another answered from the pines. A thrush&#8217;s song had never seemed such a happy melody as it did this evening.</p>
