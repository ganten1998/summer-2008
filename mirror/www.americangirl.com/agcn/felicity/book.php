				<div id="main">
					<div id="excerpt">
					<p>From <em>Meet Felicity</em></p>
						<p id="opener">Late afternoon sunshine slanted through the window onto Felicity&#8217;s back. Felicity squirmed. She had a terrible itch and didn&#8217;t know how to scratch it. She couldn&#8217;t reach it with her left hand. Her right hand was inky, because she was practicing her script. She jiggled her shoulders up and down. She held her breath and rubbed her sides with her elbows. She leaned back and wiggled her shoulder against the chair.</p>
						<p>&#8220;Felicity, my dear!&#8221; exclaimed her mother. &#8220;Why are you twitching and fidgeting so?&#8221;</p>
						<p>&#8220;I have the most awful itch, Mother,&#8221; said Felicity. &#8220;I think my stays are laced too tight today. They&#8217;re so pinching and uncomfortable.&#8221; Felicity pulled at her stays, which were laced up her back like a tight vest.</p>
						<p>Mrs. Merriman shook her head and laughed. &#8220;You think your stays are laced too tight every day! But you do grow so fast, maybe you are right. Come here, my child, and I will loosen them for you.&#8221;</p>
						<p>&#8220;Thank you, Mother,&#8221; said Felicity. She sighed with relief as her mother loosened the laces.</p>
						<p>&#8220;I&#8217;ve told you many times, Lissie. Your stays will not pinch you if you sit up straight,&#8221; said Mrs. Merriman. &#8220;And they will not be uncomfortable if you move gracefully instead of galloping about.&#8221; She straightened Felicity&#8217;s cap. &#8220;There, now, pretty one. You are set to rights. Fetch me your paper, so that I may see your handwriting practice.&#8221;</p>
						<p>Felicity blushed as she handed her mother the paper. &#8220;I haven&#8217;t quite finished it, Mother,&#8220; she said.</p>
						<p>&#8220;So I see,&#8221; said Mrs. Merriman. &#8220;The first few letters are very fine. But you lost patience when you got to the letter H. The rest of the letters go trip-trotting all over the page and then turn into sketches of horses!&#8221; She put the paper down and looked Felicity in the eye. &#8220;Lissie, what am I to do with you? You must learn to finish what you begin. If you spent half as much time on your letters as you do daydreaming of horses, you&#8217;d have the finest hand in Williamsburg.&#8221; She sighed. &#8220;Go along to the well now. Fetch some water and scrub your hand. Mind you get the ink off.&#8221;</p>
						<p>&#8220;Yes, Mother,&#8221; said Felicity. She turned to go, but stopped at the door. &#8220;Mother,&#8221; she asked. &#8220;May I help Ben make a delivery?&#8221;</p>
						<p>&#8220;Yes, my lively girl,&#8221; laughed her mother. &#8220;I know very well there&#8217;s no use trying to keep you inside when your mind is already out and away.&#8221;</p>
						<p>&#8220;Thank you, Mother!&#8221; said Felicity as she flew out the door.</p>
						<p>&#8220;Lissie! Your hat!&#8221; called her mother. But she was too late. Felicity was already halfway to the well.</p>
