				<div id="main">
					<div id="excerpt">
						<p>From <em>Meet Addy</em></p>
						<p id="opener">Just when Addy thought she could not go another step, the sky began to lighten. She could see Momma&#8217;s face for the first time in hours. It was streaked with dirt. She touched her own face and felt dried blood on her cheek from a cut below her eye.</p>
						<p>&#8220;We better stop soon, Momma,&#8221; Addy said softly. &#8220;It&#8217;s getting light out and somebody might see us.&#8221;</p>
						<p>&#8220;You right,&#8221; momma said. &#8220;We need to look for a hiding place.&#8221;</p>
						<p>They went a little farther and found a small cave. They crawled inside and huddled together, waiting for sleep to come.</p>
						<p>When they woke up hours later, it was hot. Mosquitoes buzzed around their heads, drawn to the stickiness of their sweaty skin. Addy slapped at them, but it was no use.</p>
						<p>&#8220;You must be hungry,&#8221; Momma said, reaching into her buncle. She handed Addy a piece of Auntie Lula&#8217;s cornbread. It was hard and dry, but it tasted good to Addy. She washed it down with a drink of water from the gourd.</p>
						<p>When they finished eating, Momma reached into the bundle again. &#8220;I got something for you,&#8221; she said. Addy watched eagerly as Momma opened her hand. In her palm was a small, shiny shell.</p>
						<p>&#8220;I want you to have this,&#8221; Momma said. &#8220;It&#8217;s something me and your poppa been saving for you. This cowrie shell belonged to Poppa&#8217;s grandma. She was stole from Africa when she was no bigger than you. None of her family was on the ship with her when she came here from across the water. She wore this shell on a necklace. Your poppa was gonna give it to you when you was older, but I think you should have it now, Addy. Your great-grandma&#8217;s name was Aduke. That name got a meaning where she come from. It means much loved.&#8217; I saved her name for you, Addy.&#8221;</p>
						<p>Addy was silent for a moment. Then she looked into her mother&#8217;s gentle brown eyes. &#8220;Momma, can I hold the shell tonight?&#8221;</p>
						<p>&#8220;Sure, you can. I got something special to put it on,&#8221; her mother said, pulling a leather string out of her bundle. </p>
						<p>&#8220;Momma, that&#8217;s one of Sam&#8217;s shoelaces,&#8221; Addy said.</p>
						<p>&#8220;I wanted you to have something of his, too,&#8221; her mother said. She pulled the cord through a small hole in one end of the shell, knotted it, and then put it around Addy&#8217;s neck. &#8220;Remember what I told you about the love you need to carry in your heart. It ain&#8217;t nothing you can touch like this shell, but when you find yourself feeling sad or scared, you dip into that love, Addy. It&#8217;s a well with no bottom, and it can give you strength and courage.&#8221;</p>
						<p>Addy rubbed the shell between her fingers. Its rounded top was smooth as soap. The flat underside was also smooth, except for the middle where the shell closed in on itself. There it felt like the teeth of a fine comb.</p>
						<p>&#8220;My great-grandma must have been brave to come across the water all alone. I&#8217;m gonna be brave just like she was,&#8221; Addy said.</p>
						<p>&#8220;She was brave, Addy,&#8221; Momma answered, &#8220;and you brave, too. But there&#8217;s one thing different about you and your great-grandma. Her journey ended in slavery. Yours, girl, is taking you to freedom.&#8221;</p>
